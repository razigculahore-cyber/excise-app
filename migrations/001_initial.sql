CREATE TABLE users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username TEXT NOT NULL, full_name TEXT NOT NULL DEFAULT '', password_hash TEXT NOT NULL,
 is_admin SMALLINT NOT NULL DEFAULT 0 CHECK (is_admin IN (0,1)),
 is_active SMALLINT NOT NULL DEFAULT 1 CHECK (is_active IN (0,1)),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, last_login TIMESTAMPTZ
);
CREATE UNIQUE INDEX users_username_ci ON users(lower(username));
CREATE TABLE estimates (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 title TEXT NOT NULL, summary TEXT NOT NULL DEFAULT '', total NUMERIC NOT NULL,
 inputs JSONB NOT NULL, lines JSONB NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_estimates_user ON estimates(user_id, id DESC);
CREATE TABLE audit_log (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 user_id BIGINT, username TEXT NOT NULL DEFAULT '', event TEXT NOT NULL,
 detail TEXT NOT NULL DEFAULT '', ip TEXT NOT NULL DEFAULT ''
);
CREATE TABLE failed_logins (username TEXT NOT NULL, ip TEXT NOT NULL, at DOUBLE PRECISION NOT NULL);
CREATE INDEX failed_logins_lookup ON failed_logins(lower(username), ip, at);
CREATE INDEX failed_logins_expiry ON failed_logins(at);
-- audit_log.user_id intentionally has no FK: deleted-user history must survive.
-- Flask owns authorization. Prevent Supabase REST roles from bypassing it.
REVOKE ALL ON TABLE users, estimates, audit_log, failed_logins FROM PUBLIC;
DO $$
DECLARE api_role TEXT;
BEGIN
 FOREACH api_role IN ARRAY ARRAY['anon', 'authenticated'] LOOP
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = api_role) THEN
   EXECUTE format('REVOKE ALL ON TABLE users, estimates, audit_log, failed_logins FROM %I', api_role);
   EXECUTE format('REVOKE ALL ON SEQUENCE users_id_seq, estimates_id_seq, audit_log_id_seq FROM %I', api_role);
  END IF;
 END LOOP;
END $$;
REVOKE ALL ON SEQUENCE users_id_seq, estimates_id_seq, audit_log_id_seq FROM PUBLIC;
